"""Generate src/font.h (printable ASCII 0x20..0x7e) from a Linux kernel font.

  tools/gen-font.py <linux>/lib/fonts/font_ter16x32.c > src/font.h

The kernel font file is a C array, 16x32 glyphs, 2 bytes per row, bit 7 of
the first byte is the leftmost pixel. Only the printable ASCII glyphs are kept.
"""
import re
import sys

W, H = 16, 32
FIRST, LAST = 0x20, 0x7E


def main(path):
    text = open(path).read()
    body = text[text.index("{", text.index("fontdata_")):]
    body = body[body.index("}") + 1:]  # skip the { 0, 0, FONTDATAMAX, 0 } header
    data = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body)]
    per = W // 8 * H
    if len(data) < 256 * per:
        sys.exit("unexpected font size %d" % len(data))
    out = sys.stdout
    out.write("/* SPDX-License-Identifier: GPL-2.0-only */\n")
    out.write("/*\n * Terminus 16x32, printable ASCII only. Generated by tools/gen-font.py from the\n"
              " * Linux kernel lib/fonts/font_ter16x32.c (GPL-2.0), so the titan2-boot binary\n"
              " * as a whole is distributed under GPL-2.0-only.\n */\n")
    out.write("#ifndef TITAN2_BOOT_FONT_H\n#define TITAN2_BOOT_FONT_H\n\n")
    out.write("#define FONT_W %d\n#define FONT_H %d\n#define FONT_FIRST 0x%02x\n#define FONT_LAST 0x%02x\n\n"
              % (W, H, FIRST, LAST))
    out.write("static const unsigned char font_data[%d][%d] = {\n" % (LAST - FIRST + 1, per))
    for c in range(FIRST, LAST + 1):
        g = data[c * per:(c + 1) * per]
        out.write("\t{ /* %r */\n" % chr(c))
        for i in range(0, per, 16):
            out.write("\t\t" + ", ".join("0x%02x" % b for b in g[i:i + 16]) + ",\n")
        out.write("\t},\n")
    out.write("};\n\n#endif\n")


if __name__ == "__main__":
    main(sys.argv[1])
